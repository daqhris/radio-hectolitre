#!/usr/bin/env python3
"""
Writes the link-preview (social) meta tags into every public page — Open
Graph (Facebook, LinkedIn, WhatsApp, Slack, Discord, iMessage, Bluesky, …) and
Twitter/X Card — plus the page's <meta name="description"> and canonical URL.

Why static tags, and why a script: social crawlers do not run JavaScript, and
this site fills its pages in with JS. The tags therefore have to sit in the
HTML as shipped. The text and images come from the same JSON that already
drives the rest of the site, so previews can't drift from the content:

  - hub pages (home, about, archive, episodes, works): data/site.json -> "social"
  - broadcasts: data/broadcasts/index.json + <id>.json
  - episodes / works: data/{episodes,works}/index.json + <slug>.json
  - images: the card scripts/make_share_images.py built at assets/img/og/<id|slug>.jpg
    when it exists, else the page's own artwork

Everything this script writes lives between marker comments, so re-running it
replaces its own block instead of duplicating tags. It never edits the
existing <title> (reused for og:title / twitter:title, except broadcasts —
see broadcast_page()). Standard library only.

Usage:
    python3 scripts/sync_social_meta.py            # write/refresh all pages
    python3 scripts/sync_social_meta.py --check    # verify only; exit 1 if stale or broken
    python3 scripts/sync_social_meta.py --report   # table of what every page will show

Run it after adding or editing any broadcast, episode, work, or hub-page
description. See docs/social-previews.md.
"""
import argparse
import html as htmllib
import json
import os
import re
import struct
import sys
from html.parser import HTMLParser
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BEGIN = "<!-- BEGIN social-meta: generated by scripts/sync_social_meta.py, do not hand-edit -->"
END = "<!-- END social-meta -->"

DESC_MIN, DESC_MAX = 50, 200      # outside this range a preview looks thin or gets cut off
TITLE_MAX = 70
IMAGE_WARN_BYTES = 600 * 1024     # some messaging apps skip heavier preview images
LARGE_CARD_RATIO = 1.6            # >= this width/height -> "summary_large_image"


# ---------------------------------------------------------------- helpers

def load(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return json.load(f)


def attr(text):
    """Escape for use inside a double-quoted HTML attribute."""
    return escape(text, {'"': "&quot;"})


def truncate(text, limit=160):
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:—-") + "…"


def extract_title(page_html):
    m = re.search(r"<title>(.*?)</title>", page_html, re.S)
    return htmllib.unescape(m.group(1).strip()) if m else "Radio Hectolitre"


def image_size(path):
    """(width, height, mime) for a local PNG/JPEG, read from the file header."""
    with open(path, "rb") as f:
        head = f.read(24)
        if head[:8] == b"\x89PNG\r\n\x1a\n":
            w, h = struct.unpack(">II", head[16:24])
            return w, h, "image/png"
        if head[:3] == b"\xff\xd8\xff":
            f.seek(2)
            while True:
                b = f.read(1)
                while b and b != b"\xff":
                    b = f.read(1)
                while b == b"\xff":
                    b = f.read(1)
                if not b:
                    return None
                marker = b[0]
                if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
                    continue
                (seglen,) = struct.unpack(">H", f.read(2))
                if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                    f.read(1)
                    h, w = struct.unpack(">HH", f.read(4))
                    return w, h, "image/jpeg"
                f.read(seglen - 2)
    return None


class Site:
    def __init__(self):
        self.cfg = load("data/site.json")["social"]
        self.url = self.cfg["siteUrl"].rstrip("/")
        self.name = self.cfg.get("siteName", "Radio Hectolitre")

    def abs(self, path_or_url):
        if re.match(r"^https?://", path_or_url):
            return path_or_url
        return f"{self.url}/{path_or_url.lstrip('/')}"

    def page_url(self, href):
        return f"{self.url}/" if href in ("index.html", "") else self.abs(href)


def resolve_image(site, src, alt, card=None):
    """Work out the absolute URL, dimensions and Twitter card type for an image."""
    info = {"url": site.abs(src), "alt": alt, "local": False,
            "width": None, "height": None, "mime": None, "bytes": None}
    if not re.match(r"^https?://", src):
        path = os.path.join(ROOT, src)
        if not os.path.isfile(path):
            raise FileNotFoundError(f"image not found: {src}")
        info["local"] = True
        info["bytes"] = os.path.getsize(path)
        dims = image_size(path)
        if dims:
            info["width"], info["height"], info["mime"] = dims
    if info["width"] and info["height"]:
        large = info["width"] / info["height"] >= LARGE_CARD_RATIO
    else:
        large = card == "large"   # remote image of unknown size: trust an explicit override
    info["card"] = "summary_large_image" if large else "summary"
    return info


# ---------------------------------------------------------------- page records

def generated_card(name):
    """assets/img/og/<name>.jpg if scripts/make_share_images.py has built one for this page."""
    rel = f"assets/img/og/{name}.jpg"
    return rel if os.path.isfile(os.path.join(ROOT, rel)) else None


def hub_pages(site):
    for href, spec in site.cfg["pages"].items():
        with open(os.path.join(ROOT, href), encoding="utf-8") as f:
            title = extract_title(f.read())
        yield {
            "file": href,
            "kind": "hub",
            "title": title,
            "description": spec["description"],
            "image": resolve_image(
                site,
                spec.get("image", site.cfg["defaultImage"]),
                spec.get("imageAlt", site.cfg["defaultImageAlt"]),
            ),
            "url": site.page_url(href),
        }


def broadcast_pages(site):
    for b in load("data/broadcasts/index.json")["broadcasts"]:
        hero = load(f"data/broadcasts/{b['id']}.json")["hero"]
        # The hand-written <title> of a broadcast page used to be just the date,
        # which makes a poor preview headline; build it from the data instead.
        title = f"{hero['title']} · {hero['dateLine']} — {site.name}"
        yield {
            "file": b["href"],
            "kind": "broadcast",
            "title": title,
            "description": b.get("summary") or hero.get("shortDescription", ""),
            "image": resolve_image(
                site,
                hero.get("shareImage") or generated_card(b["id"]) or hero["heroImage"],
                hero.get("shareImageAlt") or f"Poster for {hero['title']}",
            ),
            "url": site.page_url(b["href"]),
        }


def feature_pages(site, kind, index_key):
    for item in load(f"data/{kind}/index.json")[index_key]:
        detail = load(f"data/{kind}/{item['slug']}.json")
        subtitle = detail.get("subtitle", "")
        description = (
            item.get("summary")
            or (subtitle if len(subtitle) > 20 else "")
            or truncate((detail.get("synopsis") or [""])[0])
        )
        with open(os.path.join(ROOT, item["href"]), encoding="utf-8") as f:
            title = extract_title(f.read())
        yield {
            "file": item["href"],
            "kind": kind.rstrip("s"),
            "title": title,
            "description": description,
            "image": resolve_image(
                site,
                generated_card(item["slug"]) or detail["coverImage"],
                (f"{detail['title']} — {detail.get('eyebrow', 'Radio Hectolitre')}, on a background of radio-wave rings"
                 if generated_card(item["slug"]) else None)
                or detail.get("coverImageAlt") or f"Cover art for {detail['title']}",
                card=detail.get("shareCard"),
            ),
            "url": site.page_url(item["href"]),
        }


def all_pages(site):
    yield from hub_pages(site)
    yield from broadcast_pages(site)
    yield from feature_pages(site, "episodes", "episodes")
    yield from feature_pages(site, "works", "works")


# ---------------------------------------------------------------- html

def json_ld(site, page):
    """Structured data for the homepage only: lets Google show the logo and link the
    project to its other profiles. Other pages inherit the site identity from the URL."""
    org = {
        "@type": "Organization",
        "@id": f"{site.url}/#organization",
        "name": site.name,
        "url": f"{site.url}/",
        "logo": site.abs(site.cfg["logo"]),
        "sameAs": site.cfg.get("sameAs", []),
    }
    web = {
        "@type": "WebSite",
        "@id": f"{site.url}/#website",
        "name": site.name,
        "url": f"{site.url}/",
        "description": page["description"],
        "publisher": {"@id": org["@id"]},
    }
    data = {"@context": "https://schema.org", "@graph": [org, web]}
    # "</" would end the script element early; none appear today, but stay safe.
    return json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")


def build_block(site, page, with_description, with_canonical):
    img = page["image"]
    depth = page["file"].count("/")
    lines = [BEGIN]
    if with_description:
        lines.append(f'  <meta name="description" content="{attr(page["description"])}" />')
    if with_canonical:
        lines.append(f'  <link rel="canonical" href="{attr(page["url"])}" />')
    lines += [
        f'  <meta name="theme-color" content="{attr(site.cfg["themeColor"])}" />',
        f'  <link rel="manifest" href="{"../" * depth}manifest.webmanifest" />',
        '  <meta property="og:type" content="website" />',
        f'  <meta property="og:site_name" content="{attr(site.name)}" />',
        f'  <meta property="og:url" content="{attr(page["url"])}" />',
        f'  <meta property="og:title" content="{attr(page["title"])}" />',
        f'  <meta property="og:description" content="{attr(page["description"])}" />',
        f'  <meta property="og:image" content="{attr(img["url"])}" />',
    ]
    if img["mime"]:
        lines.append(f'  <meta property="og:image:type" content="{img["mime"]}" />')
    if img["width"] and img["height"]:
        lines.append(f'  <meta property="og:image:width" content="{img["width"]}" />')
        lines.append(f'  <meta property="og:image:height" content="{img["height"]}" />')
    lines += [
        f'  <meta property="og:image:alt" content="{attr(img["alt"])}" />',
        f'  <meta name="twitter:card" content="{img["card"]}" />',
        f'  <meta name="twitter:title" content="{attr(page["title"])}" />',
        f'  <meta name="twitter:description" content="{attr(page["description"])}" />',
        f'  <meta name="twitter:image" content="{attr(img["url"])}" />',
        f'  <meta name="twitter:image:alt" content="{attr(img["alt"])}" />',
    ]
    if page["file"] == "index.html":
        lines.append('  <script type="application/ld+json">')
        lines.append(json_ld(site, page))
        lines.append("  </script>")
    lines.append(END)
    return "\n".join(lines)


BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def render_page(site, page, original):
    outside = BLOCK_RE.sub("", original)
    with_description = not re.search(r'<meta\s+name="description"', outside)
    with_canonical = not re.search(r'<link\s+rel="canonical"', outside)
    block = build_block(site, page, with_description, with_canonical)
    if BEGIN in original:
        return BLOCK_RE.sub(lambda _m: block, original, count=1)
    new, n = re.subn(r"(<title>.*?</title>[ \t]*\r?\n)", lambda m: m.group(1) + block + "\n",
                     original, count=1, flags=re.S)
    if n != 1:
        raise ValueError(f"{page['file']}: no <title> line to anchor the block after")
    return new


class MetaCounter(HTMLParser):
    """Counts head meta/link tags so duplicates and gaps show up independently of the regexes."""

    def __init__(self):
        super().__init__()
        self.seen = {}
        self.in_head = True

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "body":
            self.in_head = False
        if not self.in_head:
            return
        if tag == "meta":
            key = a.get("property") or a.get("name")
            if key:
                self.seen.setdefault(key, []).append(a.get("content", ""))
        elif tag == "link" and a.get("rel") in ("canonical", "manifest"):
            self.seen.setdefault(a["rel"], []).append(a.get("href", ""))


REQUIRED = ["description", "canonical", "manifest", "theme-color", "og:type", "og:site_name", "og:url", "og:title",
            "og:description", "og:image", "og:image:alt", "twitter:card", "twitter:title",
            "twitter:description", "twitter:image", "twitter:image:alt"]


def lint(page, rendered):
    """Return (errors, warnings) for one rendered page."""
    errors, warnings = [], []
    counter = MetaCounter()
    counter.feed(rendered)
    for key in REQUIRED:
        n = len(counter.seen.get(key, []))
        if n == 0:
            errors.append(f"missing {key}")
        elif n > 1:
            errors.append(f"duplicate {key} ({n}x)")
    if page["file"] == "index.html":
        m = re.search(r'<script type="application/ld\+json">(.*?)</script>', rendered, re.S)
        try:
            json.loads(m.group(1)) if m else errors.append("missing JSON-LD on homepage")
        except ValueError as exc:
            errors.append(f"invalid JSON-LD: {exc}")
    d = len(page["description"])
    if not DESC_MIN <= d <= DESC_MAX:
        warnings.append(f"description is {d} chars (aim for {DESC_MIN}-{DESC_MAX})")
    if len(page["title"]) > TITLE_MAX:
        warnings.append(f"title is {len(page['title'])} chars (previews cut around {TITLE_MAX})")
    img = page["image"]
    if img["local"] and img["bytes"] and img["bytes"] > IMAGE_WARN_BYTES:
        warnings.append(f"image is {img['bytes'] // 1024} KB; some apps skip previews over ~{IMAGE_WARN_BYTES // 1024} KB")
    if img["card"] == "summary_large_image" and img["local"] and (img["width"], img["height"]) != (1200, 630):
        warnings.append(f"large-card image is {img['width']}x{img['height']}; 1200x630 is the safe size")
    if not img["local"]:
        warnings.append("remote image: size and availability not checked here")
    return errors, warnings


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="don't write; exit 1 if any page is stale or broken")
    mode.add_argument("--report", action="store_true", help="don't write; print what every page will show")
    args = ap.parse_args()

    site = Site()
    stale, broken, changed, total = [], [], 0, 0

    for page in all_pages(site):
        total += 1
        path = os.path.join(ROOT, page["file"])
        with open(path, encoding="utf-8") as f:
            original = f.read()
        rendered = render_page(site, page, original)
        errors, warnings = lint(page, rendered)
        is_stale = rendered != original

        if args.report:
            img = page["image"]
            size = f"{img['width']}x{img['height']}" if img["width"] else "size unknown"
            print(f"{page['file']}\n    title:  {page['title']}\n    desc:   {page['description']}"
                  f"\n    image:  {img['url']} ({size})\n    card:   {img['card']}")
            for w in warnings:
                print(f"    note:   {w}")
            for e in errors:
                print(f"    ERROR:  {e}")
            continue

        if errors:
            broken.append((page["file"], errors))
        if is_stale:
            stale.append(page["file"])
            if not args.check:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(rendered)
                changed += 1
        for w in warnings:
            if not w.startswith("remote image"):
                print(f"  note: {page['file']}: {w}")

    if args.report:
        return 0
    if args.check:
        for name in stale:
            print(f"  STALE   {name}")
        for name, errs in broken:
            print(f"  BROKEN  {name}: {'; '.join(errs)}")
        print(f"\n{total} page(s) checked: {len(stale)} stale, {len(broken)} broken.")
        return 1 if stale or broken else 0
    for name, errs in broken:
        print(f"  BROKEN  {name}: {'; '.join(errs)}")
    print(f"\n{total} page(s) processed, {changed} updated.")
    return 1 if broken else 0


if __name__ == "__main__":
    sys.exit(main())
